/** Banner for pages whose numbers are simulated samples (benchmarks, rankings). */
export function SimulatedNotice({ className, children }: { className?: string; children?: React.ReactNode }) {
  return (
    <div role="note" className={cn("flex items-start gap-3 rounded-lg border border-warning/40 bg-warning/8 px-4 py-3 text-sm", className)}>
      <FlaskConical className="mt-0.5 size-4 shrink-0 text-warning" />
      <p className="text-muted-foreground">
        <strong className="font-medium text-foreground">Simulated sample scores.</strong>{" "}
        {children ?? "No verified benchmark results are bundled with this build. Scores are generated by OneAtlas from model attributes with seeded noise to demonstrate the leaderboard; they are not measurements of real model quality."}
      </p>
    </div>
  );
}

