function hash(str: string): number {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) { h = Math.imul(h ^ str.charCodeAt(i), 3432918353); h = (h << 13) | (h >>> 19); }
  return (h ^ (h >>> 16)) >>> 0;
}
function rng(seed: number) {
  let a = seed;
  return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
const clamp = (x: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, x));

export interface ScoreInput {
  canonicalId: string; outputPrice: number | null; inputPrice: number | null; releaseYear: number | null; caps: Set<string>;
}

/** Returns the simulated score for one benchmark, or null when the model is not eligible. */
export function simulateScore(def: BenchmarkDef, m: ScoreInput): number | null {
  if (def.requires && !m.caps.has(def.requires)) return null;
  const price = m.outputPrice ?? (m.inputPrice !== null ? m.inputPrice * 3 : null);
  if (price === null) return null;
  const r = rng(hash(`${m.canonicalId}:${def.slug}`));
  const noise = (r() - 0.5) * 0.12;
  const tier = clamp((Math.log10(Math.max(price, 0.05)) + 1.3) / 3.0, 0, 1);
  const rec = m.releaseYear ? clamp((m.releaseYear - 2023) / 3.5, 0, 1) : 0.5;
  const base = 0.28 + 0.46 * tier + 0.14 * rec;
  const reasoning = m.caps.has("reasoning"), tools = m.caps.has("tool_calling");
  let q = base + noise;
  switch (def.slug) {
    case "intelligence-index": q += reasoning ? 0.06 : 0; break;
    case "coding-index": q += (tools ? 0.02 : 0) + noise * 0.4; break;
    case "reasoning-index": q += reasoning ? 0.12 : -0.04; break;
    case "agentic-index": q += (tools ? 0.04 : 0) + (reasoning ? 0.04 : 0); break;
    case "knowledge-index": q += 0.02; break;
    case "math-index": q += reasoning ? 0.1 : -0.05; break;
    case "throughput": return Number((30 + 220 * Math.pow(1 - tier, 1.3) * (0.7 + 0.6 * r())).toFixed(1));
    case "arena-elo": return Number((1000 + 380 * clamp(q, 0, 1)).toFixed(0));
  }
  return Number((100 * clamp(q, 0.05, 0.99)).toFixed(1));
}
