/**
 * Generates prisma/migrations/0001_init/migration.sql from prisma/schema.prisma.
 *
 * Why this exists: it was written in an environment where Prisma's Rust schema engine could not be
 * downloaded, so `prisma migrate dev` was unavailable. It follows Prisma's naming conventions
 * (Model_pkey, Model_col_key, Model_col_idx, Model_col_fkey) for the constructs this schema uses.
 * On a normal machine, `npx prisma migrate dev` will report any drift between this SQL and the schema.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
const src = fs
  .readFileSync(path.join(root, "prisma/schema.prisma"), "utf8")
  .split("\n")
  .map((l) => l.replace(/\/\/.*$/, "").trimEnd())
  .join("\n");

const SCALARS: Record<string, string> = {
  String: "TEXT", Int: "INTEGER", Float: "DOUBLE PRECISION", Boolean: "BOOLEAN",
  DateTime: "TIMESTAMP(3)", Decimal: "DECIMAL(65,30)", Json: "JSONB", BigInt: "BIGINT",
};

const enums = new Map<string, string[]>();
for (const m of src.matchAll(/^enum (\w+) \{([^}]*)\}/gm)) {
  enums.set(m[1], m[2].split("\n").map((s) => s.trim()).filter(Boolean));
}

interface Field {
  name: string; type: string; list: boolean; optional: boolean; attrs: string;
  kind: "scalar" | "enum" | "relation";
}
interface Model { name: string; fields: Field[]; blockAttrs: string[] }

const models: Model[] = [];
for (const m of src.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const fields: Field[] = [];
  const blockAttrs: string[] = [];
  for (const raw of m[2].split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith("@@")) { blockAttrs.push(line); continue; }
    const f = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
    if (!f) throw new Error(`Cannot parse field line: ${line}`);
    const [, name, type, list, opt, attrs] = f;
    const kind = type in SCALARS ? "scalar" : enums.has(type) ? "enum" : "relation";
    fields.push({ name, type, list: !!list, optional: !!opt, attrs, kind });
  }
  models.push({ name: m[1], fields, blockAttrs });
}
const byName = new Map(models.map((m) => [m.name, m]));

const q = (s: string) => `"${s}"`;
const splitTop = (s: string) => {
  const out: string[] = []; let depth = 0, cur = "";
  for (const ch of s) {
    if (ch === "(" || ch === "[") depth++;
    if (ch === ")" || ch === "]") depth--;
    if (ch === "," && depth === 0) { out.push(cur.trim()); cur = ""; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
};
const colName = (item: string) => item.replace(/\(.*\)$/, "").trim();

function sqlType(f: Field): string {
  if (f.kind === "enum") return q(f.type) + (f.list ? "[]" : "");
  const db = f.attrs.match(/@db\.(\w+)(?:\(([^)]*)\))?/);
  let t = SCALARS[f.type];
  if (db) {
    if (db[1] === "Date") t = "DATE";
    else if (db[1] === "Decimal") t = `DECIMAL(${db[2].replace(/\s/g, "")})`;
    else throw new Error(`Unsupported native type @db.${db[1]}`);
  }
  return t + (f.list ? "[]" : "");
}

function sqlDefault(f: Field): string | null {
  const m = f.attrs.match(/@default\(((?:[^()]|\([^)]*\))*)\)/);
  if (!m) return null;
  const v = m[1].trim();
  if (v === "now()") return "CURRENT_TIMESTAMP";
  if (/^(cuid|uuid|autoincrement)\(/.test(v)) return null;
  if (v === "true" || v === "false" || /^-?\d+(\.\d+)?$/.test(v)) return v;
  if (/^".*"$/.test(v)) return `'${v.slice(1, -1).replace(/'/g, "''")}'`;
  if (f.kind === "enum") return `'${v}'`;
  throw new Error(`Unsupported default ${v} on ${f.name}`);
}

const out: string[] = [
  "-- Generated by scripts/generate-migration.ts from prisma/schema.prisma. Do not edit by hand.",
  "",
];

for (const [name, values] of enums) {
  out.push(`-- CreateEnum\nCREATE TYPE ${q(name)} AS ENUM (${values.map((v) => `'${v}'`).join(", ")});\n`);
}

const indexSql: string[] = [];
const fkSql: string[] = [];

for (const model of models) {
  const cols: string[] = [];
  let pk: string[] = [];
  for (const f of model.fields) {
    if (f.kind === "relation") continue;
    let line = `    ${q(f.name)} ${sqlType(f)}`;
    if (!f.optional && !f.list) line += " NOT NULL";
    const d = sqlDefault(f);
    if (d !== null) line += ` DEFAULT ${d}`;
    cols.push(line);
    if (/@id\b/.test(f.attrs)) pk = [f.name];
    if (/@unique\b/.test(f.attrs)) {
      indexSql.push(`CREATE UNIQUE INDEX ${q(`${model.name}_${f.name}_key`)} ON ${q(model.name)}(${q(f.name)});`);
    }
  }
  for (const b of model.blockAttrs) {
    const inner = b.match(/^@@(\w+)\((.*)\)$/);
    if (!inner) throw new Error(`Cannot parse ${b}`);
    const [, kind, args] = inner;
    const parts = splitTop(args);
    const list = parts[0].match(/^\[(.*)\]$/);
    if (!list) throw new Error(`Bad block attr ${b}`);
    const items = splitTop(list[1]);
    const names = items.map(colName);
    const rest = parts.slice(1).join(",");
    if (kind === "id") { pk = names; continue; }
    const colsSql = items
      .map((it) => (/sort:\s*Desc/.test(it) ? `${q(colName(it))} DESC` : q(colName(it))))
      .join(", ");
    const base = `${model.name}_${names.join("_")}`;
    if (kind === "unique") {
      indexSql.push(`CREATE UNIQUE INDEX ${q(`${base}_key`)} ON ${q(model.name)}(${colsSql});`);
    } else if (kind === "index") {
      const gin = /type:\s*Gin/.test(rest);
      indexSql.push(`CREATE INDEX ${q(`${base}_idx`)} ON ${q(model.name)}${gin ? " USING GIN" : ""}(${colsSql});`);
    } else throw new Error(`Unsupported block attribute @@${kind}`);
  }
  if (!pk.length) throw new Error(`${model.name} has no primary key`);
  cols.push(`    CONSTRAINT ${q(`${model.name}_pkey`)} PRIMARY KEY (${pk.map(q).join(", ")})`);
  out.push(`-- CreateTable\nCREATE TABLE ${q(model.name)} (\n${cols.join(",\n")}\n);\n`);

  for (const f of model.fields) {
    if (f.kind !== "relation" || f.list) continue;
    const rel = f.attrs.match(/@relation\(([^)]*(?:\[[^\]]*\][^)]*)*)\)/);
    if (!rel || !/fields:/.test(rel[1])) continue;
    const from = rel[1].match(/fields:\s*\[([^\]]*)\]/)![1].split(",").map((s) => s.trim());
    const to = rel[1].match(/references:\s*\[([^\]]*)\]/)![1].split(",").map((s) => s.trim());
    const od = rel[1].match(/onDelete:\s*(\w+)/)?.[1];
    const target = byName.get(f.type);
    if (!target) throw new Error(`Unknown relation target ${f.type}`);
    const fromOptional = from.some((n) => model.fields.find((x) => x.name === n)?.optional);
    const action = od ?? (fromOptional ? "SetNull" : "Restrict");
    const sqlAction = { Cascade: "CASCADE", Restrict: "RESTRICT", SetNull: "SET NULL", NoAction: "NO ACTION" }[action];
    if (!sqlAction) throw new Error(`Unsupported onDelete ${action}`);
    fkSql.push(
      `ALTER TABLE ${q(model.name)} ADD CONSTRAINT ${q(`${model.name}_${from.join("_")}_fkey`)} ` +
        `FOREIGN KEY (${from.map(q).join(", ")}) REFERENCES ${q(f.type)}(${to.map(q).join(", ")}) ` +
        `ON DELETE ${sqlAction} ON UPDATE CASCADE;`,
    );
  }
}

out.push("-- CreateIndex", ...indexSql, "", "-- AddForeignKey", ...fkSql, "");

const dir = path.join(root, "prisma/migrations/0001_init");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "migration.sql"), out.join("\n"));
fs.writeFileSync(path.join(root, "prisma/migrations/migration_lock.toml"),
  '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
console.log(`models=${models.length} enums=${enums.size} indexes=${indexSql.length} fks=${fkSql.length}`);
